def _domain_hits(text: str) -> list[str]:
    lowered = (text or "").lower()
    hits = []
    for name, domain in DOMAINS.items():
        if any(word.lower() in lowered for word in domain["keywords"]):
            hits.append(name)
    for word, name in BODY_DOMAIN.items():
        if word in lowered and name not in hits:
            hits.append(name)
    if not hits:
        from .semantics import infer_domain
        inferred = infer_domain(text)
        if inferred:
            hits.append(inferred)
    return hits


def detect(text: str) -> list[str]:
    return _domain_hits(text)


def expand(text: str) -> str:
    lowered = (text or "").lower()
    extra: list[str] = []
    for canonical, variants in SYNONYM_MAP.items():
        if canonical in lowered:
            continue
        if any(variant in lowered for variant in variants):
            extra.append(canonical)
    return (text + " " + " ".join(dict.fromkeys(extra))).strip()


def all_keywords() -> list[str]:
    words: list[str] = []
    for domain in DOMAINS.values():
        words.extend(domain["keywords"])
        words.extend(domain["canonical"])
    return list(dict.fromkeys(words))


def _is_dizziness_only(text: str) -> bool:
    lowered = text or ""
    dizzy = any(word in lowered for word in
                ("头晕", "眩晕", "晕乎乎", "头昏", "眼前发黑", "站不稳",
                 "发晕", "晕得慌"))
    if not dizzy and "头" in lowered and "晕" in lowered:
        dizzy = True
    head_pain = any(word in lowered for word in
                    ("头痛", "头疼", "偏头痛", "太阳穴", "后脑勺疼", "脑袋疼"))
    return dizzy and not head_pain


