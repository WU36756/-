def followups_for(text: str) -> list[dict[str, Any]]:
    if _is_dizziness_only(text):
        return DIZZINESS_FOLLOWUPS
    hits = _domain_hits(text)
    if not hits:
        return [
            {"id": "general_site", "question": "具体哪里不舒服？",
             "options": {"头面部": "头面部", "胸腹": "胸腹", "四肢": "四肢", "全身": "全身"}},
            {"id": "general_days", "question": "持续多久了？",
             "options": {"1-2 天": "1-2 天", "3-5 天": "3-5 天", "一周以上": "一周以上"}},
        ]
    questions: list[dict[str, Any]] = []
    for name in hits[:3]:
        questions.extend(DOMAINS[name]["followups"])
    seen: set[str] = set()
    unique = []
    for question in questions:
        if question["id"] in seen:
            continue
        seen.add(question["id"])
        unique.append(question)
    return unique[:5]


